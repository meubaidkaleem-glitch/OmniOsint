"""The simulated provider: a stand-in used to test the collection pipeline.

It is disabled unless ``collection.enable_simulated_provider`` is set. Its data
is generated from a hash of the input and uses only reserved documentation
values (RFC 5737 and RFC 3849 addresses, RFC 2606 ``.example`` names and
RFC 5398 AS numbers), so it can never be mistaken for, or collide with, a real
observation. The framework marks everything it produces as simulated; the
adapter cannot turn that off.

``options["simulate"]`` makes it fail in a chosen way, to exercise the
failure handling: ``timeout``, ``unavailable``, ``rate_limited``, ``quota``,
``auth``, ``malformed``, ``empty``, ``partial``, ``flaky`` (fails on the first
attempt only) and ``slow`` (takes ``options["delay"]`` seconds).
"""

from __future__ import annotations

import asyncio
import hashlib
import json
from datetime import UTC, datetime
from typing import Any

from omniosint.indicators.types import TYPE_INFO, EntityType, IndicatorType
from omniosint.providers.base import (
    Capability,
    CollectionContext,
    Cost,
    CostKind,
    HealthResult,
    Indicator,
    IntelligenceProvider,
    Observation,
    Operation,
    ProviderMetadata,
    Quota,
    RateLimit,
    RawPage,
    RawResult,
    RelatedEntity,
)
from omniosint.providers.errors import (
    ProviderAuthFailed,
    ProviderMalformedResponse,
    ProviderQuotaExceeded,
    ProviderRateLimited,
    ProviderTimeout,
    ProviderUnavailable,
)

NOTICE = "Simulated data generated by OmniOSINT for testing. It describes nothing real."
FAILURE_MODES = frozenset(
    {
        "timeout",
        "unavailable",
        "rate_limited",
        "quota",
        "auth",
        "malformed",
        "empty",
        "partial",
        "flaky",
        "slow",
    }
)
_TEXT_TYPES = frozenset(info.type for info in TYPE_INFO.values() if info.input_kind == "text") - {
    IndicatorType.QUESTION
}
_NETWORK_TARGETS = frozenset(
    {
        IndicatorType.DOMAIN,
        IndicatorType.URL,
        IndicatorType.IPV4,
        IndicatorType.IPV6,
        IndicatorType.IP_RANGE,
    }
)

LOOKUP = Capability(
    id="simulated.lookup",
    name="Simulated lookup",
    description="Returns generated records for any text indicator. Passive and free.",
    accepts=_TEXT_TYPES,
    operation=Operation.LOOKUP,
    cache_ttl_seconds=3600,
    timeout_seconds=10.0,
)
PAID_LOOKUP = Capability(
    id="simulated.paid_lookup",
    name="Simulated paid lookup",
    description="Like the simulated lookup, but declared as costing one credit per call.",
    accepts=_TEXT_TYPES,
    operation=Operation.LOOKUP,
    cost=Cost(
        CostKind.CREDITS, credits_per_call=1.0, note="Simulated credits; nothing is charged."
    ),
    cache_ttl_seconds=3600,
    timeout_seconds=10.0,
)
PROBE = Capability(
    id="simulated.probe",
    name="Simulated active probe",
    description=(
        "Declared as contacting the target, so it needs an approved scope. It contacts "
        "nothing: the probe results are generated."
    ),
    accepts=_NETWORK_TARGETS,
    operation=Operation.DISCOVERY,
    cache_ttl_seconds=0,
    timeout_seconds=10.0,
)


def _digest(text: str) -> bytes:
    return hashlib.sha256(text.encode("utf-8")).digest()


def _documentation_ipv4(seed: bytes, index: int) -> str:
    return f"192.0.2.{(seed[index] % 254) + 1}"


def _documentation_host(seed: bytes, index: int) -> str:
    return f"host-{seed[index : index + 3].hex()}.simulated.example"


class SimulatedProvider(IntelligenceProvider):
    metadata = ProviderMetadata(
        id="simulated",
        name="Simulated provider",
        category="development",
        version="1.0",
        description=(
            "Generates labelled test data to exercise the collection pipeline. "
            "Disabled unless collection.enable_simulated_provider is set."
        ),
        capabilities=(LOOKUP, PAID_LOOKUP, PROBE),
        rate_limit=RateLimit(requests=20, per_seconds=1.0, burst=20),
        source_kind="simulated",
        simulated=True,
        terms_note=NOTICE,
    )

    async def health_check(self, context: CollectionContext) -> HealthResult:
        return HealthResult(
            status="ok", detail="Simulated provider: always available.", latency_ms=0.0
        )

    async def get_quota(self, context: CollectionContext) -> Quota | None:
        return Quota(plan="simulated", remaining=None, unit="credits")

    async def collect(self, indicator: Indicator, context: CollectionContext) -> RawResult:
        mode = str(context.options.get("simulate") or "")
        if mode == "timeout":
            raise ProviderTimeout("Simulated timeout.")
        if mode == "unavailable":
            raise ProviderUnavailable("Simulated outage (HTTP 503).")
        if mode == "rate_limited":
            raise ProviderRateLimited("Simulated rate limit (HTTP 429).", retry_after=1)
        if mode == "quota":
            raise ProviderQuotaExceeded("Simulated quota exhaustion.")
        if mode == "auth":
            raise ProviderAuthFailed("Simulated rejection of the credentials (HTTP 401).")
        if mode == "flaky" and context.attempt <= 1:
            raise ProviderUnavailable("Simulated transient failure on the first attempt.")
        if mode == "slow":
            await asyncio.sleep(float(context.options.get("delay", 1.0)))
        if mode == "malformed":
            return RawResult(pages=(self._page(b'{"records": [ this is not JSON', indicator),))

        requested_pages = int(context.options.get("pages", 1))
        pages_to_make = max(1, min(requested_pages, context.max_pages))
        seed = _digest(f"{context.capability.id}:{indicator.type}:{indicator.value}")
        pages: list[RawPage] = []
        for number in range(1, pages_to_make + 1):
            if mode == "partial" and number == 2:
                return RawResult(
                    pages=tuple(pages),
                    truncated=True,
                    truncation_reason="Page 2 failed (simulated outage); page 1 was kept.",
                )
            records = (
                []
                if mode == "empty"
                else self._records(indicator, context.capability, seed, number)
            )
            body = {
                "simulated": True,
                "notice": NOTICE,
                "capability": context.capability.id,
                "query": {"type": indicator.type.value, "value": indicator.value},
                "page": number,
                "pages": pages_to_make,
                "records": records,
            }
            pages.append(self._page(json.dumps(body, sort_keys=True).encode("utf-8"), indicator))
            await context.progress({"page": number, "pages": pages_to_make})
        truncated = requested_pages > pages_to_make
        return RawResult(
            pages=tuple(pages),
            truncated=truncated,
            truncation_reason=f"Stopped at the page limit ({pages_to_make})."
            if truncated
            else None,
        )

    def _page(self, content: bytes, indicator: Indicator) -> RawPage:
        return RawPage(
            content=content,
            content_type="application/json",
            received_at=datetime.now(UTC),
            status_code=200,
            source_url=None,
        )

    def _records(
        self, indicator: Indicator, capability: Capability, seed: bytes, page: int
    ) -> list[dict[str, Any]]:
        offset = (page - 1) * 4
        fingerprint = seed[offset : offset + 8].hex()
        if capability.id == PROBE.id:
            port = (80, 443, 8080, 8443)[seed[offset] % 4]
            return [
                {
                    "kind": "simulated.open_port",
                    "id": f"sim-{fingerprint}",
                    "port": port,
                    "protocol": "tcp",
                    "address": _documentation_ipv4(seed, offset),
                }
            ]
        return [
            {
                "kind": "simulated.attribute",
                "id": f"sim-{fingerprint}",
                "fingerprint": fingerprint,
                "label": f"Simulated attribute {fingerprint[:4]}",
            },
            {
                "kind": "simulated.related_address",
                "id": f"sim-{fingerprint}-a",
                "address": _documentation_ipv4(seed, offset + 1),
            },
            {
                "kind": "simulated.related_host",
                "id": f"sim-{fingerprint}-h",
                "host": _documentation_host(seed, offset + 2),
            },
        ]

    def normalize(
        self, indicator: Indicator, capability: Capability, raw: RawResult
    ) -> list[Observation]:
        entity_type = (
            indicator.entity_type
            or TYPE_INFO[indicator.type].entity_type
            or EntityType.THREAT_INDICATOR
        )
        observations: list[Observation] = []
        for number, page in enumerate(raw.pages, start=1):
            try:
                body = json.loads(page.content)
                records = body["records"]
                if body.get("simulated") is not True or not isinstance(records, list):
                    raise ValueError("unexpected structure")
            except (ValueError, KeyError, TypeError) as error:
                raise ProviderMalformedResponse(
                    f"Page {number} is not the expected JSON: {type(error).__name__}."
                ) from error
            for index, record in enumerate(records):
                observations.append(
                    self._observation(indicator, entity_type, record, number, index, page)
                )
        return observations

    def _observation(
        self,
        indicator: Indicator,
        entity_type: EntityType,
        record: dict[str, Any],
        page_number: int,
        index: int,
        page: RawPage,
    ) -> Observation:
        kind = record.get("kind")
        if not isinstance(kind, str):
            raise ProviderMalformedResponse(f"Record {index} on page {page_number} has no kind.")
        related: list[RelatedEntity] = []
        attributes: dict[str, Any] = {"simulated": True}
        if kind == "simulated.related_address":
            related.append(
                RelatedEntity(
                    type=EntityType.IP_ADDRESS,
                    value=record["address"],
                    relation="observed_alongside",
                )
            )
        elif kind == "simulated.related_host":
            related.append(
                RelatedEntity(
                    type=EntityType.DOMAIN, value=record["host"], relation="observed_alongside"
                )
            )
        elif kind == "simulated.open_port":
            attributes.update(port=record["port"], protocol=record["protocol"])
            related.append(
                RelatedEntity(
                    type=EntityType.IP_ADDRESS, value=record["address"], relation="probed_at"
                )
            )
        else:
            attributes.update(fingerprint=record.get("fingerprint"), label=record.get("label"))
        return Observation(
            kind=kind,
            entity_type=entity_type,
            entity_value=indicator.value,
            entity_display=indicator.display,
            attributes=attributes,
            related=tuple(related),
            observed_at=page.received_at,
            provider_object_id=record.get("id"),
            page=page_number,
            raw_pointer=f"/records/{index}",
            original=record,
        )
