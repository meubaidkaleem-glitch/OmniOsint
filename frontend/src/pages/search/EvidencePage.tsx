import { useState } from "react";
import { Link, useParams } from "react-router";

import { useEvidence, useRawEvidence } from "@/api/queries";
import { useCan } from "@/app/context";
import { Button } from "@/components/ui/button";
import { ErrorState, Notice } from "@/components/ui/feedback";
import { Checkbox } from "@/components/ui/form";
import { Badge, DefinitionList, Panel, Skeleton } from "@/components/ui/surface";
import { formatDateTime } from "@/lib/format";

interface RelatedEntry {
  type: string;
  value: string;
  relation: string;
  entity_id?: string;
  rejected?: string;
}

export function EvidencePage() {
  const { evidenceId = "" } = useParams();
  const detail = useEvidence(evidenceId);
  const can = useCan();
  const [showRaw, setShowRaw] = useState(false);
  const [unmasked, setUnmasked] = useState(false);
  const raw = useRawEvidence(evidenceId, unmasked, showRaw);

  if (detail.isPending) return <Skeleton className="h-64" />;
  if (detail.isError) return <ErrorState error={detail.error} onRetry={() => void detail.refetch()} />;
  const { evidence, entity, source, integrity } = detail.data;
  const attributes = (evidence.normalized.attributes as Record<string, unknown> | undefined) ?? {};
  const related = (evidence.normalized.related as RelatedEntry[] | undefined) ?? [];

  return (
    <div className="space-y-5">
      {evidence.is_simulated ? (
        <Notice tone="warn" title="Simulated evidence">
          This record was generated by the simulated provider for testing. It describes nothing real.
        </Notice>
      ) : null}
      <div className="grid gap-5 lg:grid-cols-2">
        <Panel title="Observation" description={evidence.observation_kind}>
          <DefinitionList
            items={[
              ["Entity", `${entity.label}: ${entity.display_name}`],
              ...Object.entries(attributes).map(([key, value]): [string, string] => [
                key.replaceAll("_", " "),
                typeof value === "object" ? JSON.stringify(value) : String(value),
              ]),
            ]}
          />
          {related.length ? (
            <div className="mt-4">
              <h3 className="mb-1.5 text-xs font-semibold uppercase tracking-wide text-fg-subtle">
                Mentions (candidate relationships, not confirmed links)
              </h3>
              <ul className="space-y-1 text-sm">
                {related.map((entry) => (
                  <li key={`${entry.type}:${entry.value}`}>
                    <span className="text-fg-muted">{entry.relation.replaceAll("_", " ")}</span>{" "}
                    {entry.type.replaceAll("_", " ")} <code>{entry.value}</code>
                    {entry.rejected ? <span className="ml-2 text-xs text-warn">{entry.rejected}</span> : null}
                  </li>
                ))}
              </ul>
            </div>
          ) : null}
        </Panel>
        <Panel title="Provenance">
          <DefinitionList
            items={[
              ["Source", source ? `${source.name} (${source.kind})` : evidence.source_id],
              ...(source?.upstream_source_ids.length
                ? [["Derived from", source.upstream_source_ids.join(", ")] as [string, string]]
                : []),
              ["Collected", formatDateTime(evidence.collected_at)],
              ["Observed", formatDateTime(evidence.observed_at)],
              ["Provider object", evidence.provider_object_id ?? "-"],
              [
                "Job",
                evidence.job_id ? <code key="job">{evidence.job_id}</code> : "-",
              ],
              ["Transformations", evidence.transformation_history.map((step) => `${String(step.step)} by ${String(step.by)}`).join("; ")],
              ["Verification", evidence.verification_status],
            ]}
          />
        </Panel>
      </div>
      <Panel title="Integrity" description={integrity.detail}>
        <div className="flex flex-wrap gap-2 text-sm">
          <Badge tone={integrity.content_hash_valid ? "ok" : "danger"}>
            Content {integrity.content_hash_valid ? "matches its hash" : "does not match its hash"}
          </Badge>
          <Badge tone={integrity.raw_available ? (integrity.raw_hash_valid ? "ok" : "danger") : "neutral"}>
            {integrity.raw_available
              ? integrity.raw_hash_valid
                ? "Raw response matches its hash"
                : "Raw response altered"
              : "Raw response not stored"}
          </Badge>
        </div>
        <p className="mt-3 break-all text-xs text-fg-subtle">
          Content hash {evidence.content_hash}
          {evidence.raw_sha256 ? ` · raw response SHA-256 ${evidence.raw_sha256}` : ""}
        </p>
      </Panel>
      <Panel
        title="Raw response"
        description="As the provider sent it. Fields that look like credentials are masked unless you choose otherwise."
        actions={
          <Button size="sm" onClick={() => setShowRaw(true)} disabled={showRaw || !integrity.raw_available}>
            Show
          </Button>
        }
      >
        {can("evidence:read_raw") ? (
          <Checkbox
            label="Show unmasked"
            description="Recorded in the audit trail."
            checked={unmasked}
            onChange={(event) => setUnmasked(event.target.checked)}
          />
        ) : null}
        {showRaw ? (
          raw.isPending ? (
            <Skeleton className="mt-3 h-32" />
          ) : raw.isError ? (
            <ErrorState error={raw.error} />
          ) : (
            <pre className="mt-3 max-h-[32rem] overflow-auto rounded-md border border-line bg-surface-2 p-3 text-xs">
              {raw.data.format === "json" ? JSON.stringify(raw.data.body, null, 2) : String(raw.data.body)}
            </pre>
          )
        ) : null}
      </Panel>
      <p className="text-xs text-fg-subtle">
        <Link to="/search/history" className="hover:underline">
          Back to collection history
        </Link>
      </p>
    </div>
  );
}
